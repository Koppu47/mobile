export function getFluidRequirementsForVariant(variantId: string): VariantFluidRequirement | null {
  if (VARIANT_FLUID_SPECS[variantId]) {
    return VARIANT_FLUID_SPECS[variantId];
  }
  const variant = VEHICLE_VARIANTS.find(v => v.id === variantId);
  if (variant) {
    const sibling = VEHICLE_VARIANTS.find(v => v.generationId === variant.generationId && VARIANT_FLUID_SPECS[v.id]);
    if (sibling && VARIANT_FLUID_SPECS[sibling.id]) {
      return {
        ...VARIANT_FLUID_SPECS[sibling.id],
        variantId,
      };
    }
  }
  const keys = Object.keys(VARIANT_FLUID_SPECS);
  return VARIANT_FLUID_SPECS[keys[0]] || null;
}
